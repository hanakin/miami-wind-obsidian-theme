// Step 1: builds capture/checklist.json and capture/CHECKLIST.md from the running app.
// Usage: bun run capture:checklist [--refresh]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { type AppInventory, type CommandResult, classifyCommands, inventory } from "./discover.ts";
import { install } from "./engine.ts";
import { close, launch, verifyIsolation } from "./obsidian.ts";
import {
	allScenes,
	appClassStatuses,
	appSelectors,
	CAPTURE,
	checklistItems,
	loadExclusions,
	plannedCoverage,
	platformChecklistItems,
	themeExclusion,
	themeSelectors,
} from "./plan.ts";
import type { Target } from "./types.ts";

if (!existsSync(`${CAPTURE}.app/app.css`)) {
	throw new Error("Run `bun run capture:extract-app-css` first.");
}

// --refresh rebuilds from the inventory and command probe already in checklist.json.
const refresh = process.argv.includes("--refresh");
if (refresh) {
	const prev = JSON.parse(readFileSync(`${CAPTURE}checklist.json`, "utf8")) as {
		isolation: string[];
		inventory: AppInventory;
		commands: CommandResult[];
	};
	write(prev.isolation, prev.inventory, prev.commands, prev.inventory.version);
} else {
	const session = await launch();
	try {
		const isolation = verifyIsolation(session.proc.pid ?? 0);
		await install(session.page);
		const inv = await inventory(session.page);
		console.log(
			`Obsidian ${inv.version}: ${inv.commands.length} commands, ${inv.settingTabs.length} settings tabs, ${inv.views.length} views`,
		);
		const commands = await classifyCommands(session, session.page, inv);
		write(isolation, inv, commands, inv.version);
	} finally {
		await close(session);
	}
}

function write(
	isolation: string[],
	inv: AppInventory,
	commands: CommandResult[],
	version: string,
): void {
	const scenes = allScenes(inv, commands, () => null);
	const items = [...checklistItems(scenes), ...platformChecklistItems()];
	const theme = themeSelectors();
	const ex = loadExclusions();
	const planned = plannedCoverage(theme, items);
	const appClasses = appClassStatuses(appSelectors(), ex);
	const checklist = {
		obsidianVersion: version,
		generated: new Date().toISOString(),
		isolation,
		inventory: inv,
		commands,
		items,
		themeSelectors: theme.map((s) => ({
			...s,
			planned: planned.get(s.id) ?? [],
			...(themeExclusion(s.selector, ex) ? { excluded: themeExclusion(s.selector, ex) } : {}),
		})),
		appClasses,
	};
	writeFileSync(`${CAPTURE}checklist.json`, `${JSON.stringify(checklist, null, "\t")}\n`);
	writeFileSync(`${CAPTURE}CHECKLIST.md`, markdown(checklist));
	const surfaces = new Set(items.map((i) => i.surface));
	console.log(
		`Checklist: ${items.length} items on ${surfaces.size} surfaces; ${theme.length} theme selectors; ${appClasses.length} app classes (${appClasses.filter((c) => c.excluded).length} excluded so far)`,
	);
}

function t(target: Target): string {
	const s = typeof target === "string" ? target : JSON.stringify(target);
	return `\`${s.replaceAll("|", "\\|").replaceAll("`", "'")}\``;
}

function markdown(c: {
	obsidianVersion: string;
	generated: string;
	isolation: string[];
	commands: Awaited<ReturnType<typeof classifyCommands>>;
	items: ReturnType<typeof checklistItems>;
	themeSelectors: { id: string; selector: string; planned: string[]; excluded?: string }[];
	appClasses: { name: string; excluded?: string }[];
}): string {
	const out: string[] = [];
	out.push("# Miami Wind capture checklist", "");
	out.push(
		`Generated by \`bun run capture:checklist\` from Obsidian ${c.obsidianVersion} (desktop, Linux) on ${c.generated.slice(0, 10)}. Machine-readable copy: \`checklist.json\`. Actual coverage after capture: \`COVERAGE.md\` (from \`bun run capture:coverage\`).`,
		"",
		"## Run conditions",
		"",
		"- Obsidian version: the newest `obsidian-<version>.asar` in `~/Work/miami-wind-obsidian-capture/` (a read-only copy of the self-updated asar in `~/.config/obsidian/`), placed in the isolated user-data dir so the packaged loader runs it.",
		'- Appearance: `vault/.obsidian/appearance.json` is a copy of Mike\'s (`cssTheme: Miami Wind`, `showRibbon: true`, everything else default: base theme "system", default accent, default fonts and size, default hidden frame, zoom 0). The headless window gets `--force-dark-mode` so "system" resolves to dark as on his desktop.',
		'- Fonts: theme.css asks for "CaskaydiaMono Nerd Font" (code), which is not installed on Atlantis; code renders in the fallback monospace font. "Liberation Sans" is installed.',
		"- Window: 1600×1000, device scale 1, Chromium headless Ozone (no window on any screen).",
		"- macOS / Windows: items `platform.<os>.<line:index>` list every app.css selector that needs `body.mod-macos` or `body.mod-windows`. The capture covers them with synthetic variants: a Linux fixture with the platform class swapped in (no screenshot).",
		"",
	);
	out.push(
		`- Items: **${c.items.length}**`,
		`- Commands probed: **${c.commands.length}** (${c.commands.filter((x) => !["none", "unavailable", "skipped"].includes(x.outcome.kind)).length} open their own UI)`,
		`- theme.css selectors: **${c.themeSelectors.length}**`,
		`- Classes in Obsidian's app.css: **${c.appClasses.length}** (${c.appClasses.filter((x) => x.excluded).length} excluded by rule before capture)`,
		"",
	);
	out.push(
		"## How coverage is proven",
		"",
		"- Each item has a scene (how to reach it in the app) and a target element. `bun run capture:run` reaches it in an isolated Obsidian, saves the element with its ancestor wrappers and the html/body classes to `fixtures/<item>.html`, and a screenshot to `~/Work/miami-wind-obsidian-capture/screenshots/<item>.png`.",
		'- Interactive states (hover, active, focus, focus-visible, focus-within) are forced through the DevTools protocol (`CSS.forcePseudoState`). The forced element carries `data-capture-state="<state>"` in its fixture. App-driven states (`is-active`, `is-selected`, collapsed, ...) are real classes set by Obsidian.',
		"- `bun run capture:coverage` matches every theme.css selector against every fixture in Chromium. `:hover`/`:active` match an element marked with that state or containing one; `:focus` matches focus or focus-visible marks; `::selection` needs a `selection` mark; `::-webkit-scrollbar-*:hover` needs `scrollbar-hover`; other pseudo-elements are dropped (they render on the element that remains).",
		"- App classes count as covered when any fixture contains them. A class is excluded when every app.css rule using it is gated to a context we do not run (mobile, macOS, Windows, right-to-left, print, forced colors) or when `exclusions.json` gives a reason.",
		"",
	);
	out.push("## Items by surface", "");
	const bySurface = new Map<string, typeof c.items>();
	for (const i of c.items) bySurface.set(i.surface, [...(bySurface.get(i.surface) ?? []), i]);
	for (const [surface, list] of [...bySurface.entries()].sort()) {
		out.push(
			`### ${surface} (${list.length})`,
			"",
			"| Item | Component | State | Target |",
			"| --- | --- | --- | --- |",
		);
		for (const i of list)
			out.push(`| \`${i.id}\` | ${i.component} | ${i.state} | ${t(i.target)} |`);
		out.push("");
	}
	out.push(
		"## Commands",
		"",
		"Every command in the app, run once in the first context that accepts it.",
		"",
	);
	out.push("| Command | Name | Context | Outcome |", "| --- | --- | --- | --- |");
	for (const x of c.commands) {
		const o = x.outcome;
		const desc =
			o.kind === "skipped"
				? `skipped: ${o.reason}`
				: o.kind === "view"
					? `view \`${o.type}\``
					: o.kind === "state"
						? `body classes ${o.classes.join(" ")}`
						: o.kind === "window"
							? "new window"
							: o.kind === "none"
								? "no own UI (editing or navigation action)"
								: o.kind;
		out.push(`| \`${x.id}\` | ${x.name.replaceAll("|", "/")} | ${x.context ?? ""} | ${desc} |`);
	}
	out.push(
		"",
		"## theme.css selectors",
		"",
		"Planned items name the selector's key class; `COVERAGE.md` lists the fixtures that really match.",
		"",
	);
	out.push("| Line | Selector | Planned items |", "| --- | --- | --- |");
	for (const s of c.themeSelectors) {
		const plan = s.excluded
			? `excluded: ${s.excluded}`
			: s.planned.map((p) => `\`${p}\``).join(", ") || "matched by coverage";
		out.push(`| ${s.id} | \`${s.selector.replaceAll("|", "\\|")}\` | ${plan} |`);
	}
	out.push("", "## App classes excluded before capture", "");
	const reasons = new Map<string, string[]>();
	for (const a of c.appClasses)
		if (a.excluded) reasons.set(a.excluded, [...(reasons.get(a.excluded) ?? []), a.name]);
	for (const [why, names] of reasons)
		out.push(`- **${why}** (${names.length}): ${names.map((n) => `\`${n}\``).join(" ")}`);
	out.push("");
	return out.join("\n");
}
